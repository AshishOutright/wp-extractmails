<script>
  const items = document.querySelectorAll(".faq-item");

  items.forEach((item, index) => {
    item.addEventListener("click", () => {

      items.forEach((el, i) => {
        const content = el.querySelector(".faq-content");
        const icon = el.querySelector("span");

        if (i === index) {
          const isOpen = content.classList.contains("max-h-[200px]");

          // Close all
          items.forEach(e => {
            e.querySelector(".faq-content").classList.remove("max-h-[200px]", "opacity-100");
            e.querySelector(".faq-content").classList.add("max-h-0", "opacity-0");
            e.querySelector("span").textContent = "+";
          });

          // Open clicked
          if (!isOpen) {
            content.classList.remove("max-h-0", "opacity-0");
            content.classList.add("max-h-[200px]", "opacity-100");
            icon.textContent = "−";
          }

        }
      });

    });
  });
